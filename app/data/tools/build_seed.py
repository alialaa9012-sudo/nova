"""Generate supabase/seed.sql from the approved data files in app/data.

Usage:  python3 -I data/tools/build_seed.py            (from app/)
        python3 -I data/tools/build_seed.py --check    (fails if seed.sql is out of date)

Menu rows with status=excluded are skipped. Zones are all loaded; only "ok" and "review"
zones are active, "pending" zones are stored inactive so the owner can fix them later.
"""
import argparse
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.dirname(HERE)
OUT = os.path.join(os.path.dirname(DATA), "supabase", "seed.sql")
DOW = {"sun": 0, "mon": 1, "tue": 2, "wed": 3, "thu": 4, "fri": 5, "sat": 6}


def q(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def rows(name):
    with open(os.path.join(DATA, name), encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def build():
    meta = json.load(open(os.path.join(DATA, "branches.json"), encoding="utf-8"))
    out = [
        "-- Generated by app/data/tools/build_seed.py from app/data. Do not edit by hand.",
        "-- Run once on an empty database, after the migrations.",
        "begin;",
        "",
        "insert into public.app_settings (key, value) values",
        "  ('brand', " + q(json.dumps({
            "name_ar": meta["brand"]["name_ar"],
            "name_en": meta["brand"]["name_en"],
            "whatsapp": meta["brand"]["whatsapp"],
            "logo_url": meta["brand"]["logo"]["url_path"],
        }, ensure_ascii=False)) + "::jsonb);",
        "",
    ]

    branch_values, hour_values = [], []
    for i, b in enumerate(meta["branches"], start=1):
        c = b["online_charges"]
        branch_values.append("  (" + ", ".join([
            q(b["id"]), q(b["order_code_proposed"]), q(b["name_ar"]), q(b["address_ar"]),
            "array[" + ", ".join(q(p) for p in b["phones"]) + "]::text[]",
            q(b["maps_url"]), q(b["lat"]), q(b["lng"]), q(b["timezone"]),
            q(c["service_percent"]), q(c["tax_percent"]), q(c["tax_base"]), q(i)]) + ")")
        for day, h in b["working_hours"].items():
            hour_values.append(f"  ({q(b['id'])}, {DOW[day]}, {q(h['opens'])}, {q(h['closes'])}, {q(h['crosses_midnight'])})")
    out += [
        "insert into public.branches (id, code, name_ar, address_ar, phones, maps_url, lat, lng, timezone,"
        " service_percent, tax_percent, tax_base, sort_order) values",
        ",\n".join(branch_values) + ";", "",
        "insert into public.branch_hours (branch_id, weekday, opens_at, closes_at, crosses_midnight) values",
        ",\n".join(hour_values) + ";", "",
    ]

    cat_values, item_values, size_values = [], [], []
    counts = {}
    for b in meta["branches"]:
        bid = b["id"]
        cats, items = [], {}
        for r in rows(b["menu_file"]):
            if r["status"] == "excluded":
                continue
            if r["category"] not in cats:
                cats.append(r["category"])
            key = (r["category"], r["item"])
            if key not in items:
                items[key] = {"desc": r["description"], "adv": r["advance_notice_hours"], "review": False, "sizes": []}
            items[key]["sizes"].append((r["size_label"], r["price"]))
            if r["status"] == "check":
                items[key]["review"] = True
        for n, c in enumerate(cats, start=1):
            cat_values.append(f"  ({q(bid)}, {q(c)}, {n})")
        for n, ((cat, name), it) in enumerate(items.items(), start=1):
            adv = f"{int(it['adv'])}::int" if it["adv"] else "null::int"
            item_values.append(f"  ({q(bid)}, {q(cat)}, {q(name)}, {q(it['desc'])}, {adv}, {q(it['review'])}, {n})")
            for k, (label, price) in enumerate(it["sizes"], start=1):
                size_values.append(f"  ({q(bid)}, {q(cat)}, {q(name)}, {q(label)}, {price}::numeric, {k})")
        counts[bid] = {"categories": len(cats), "items": len(items), "sizes": sum(len(i["sizes"]) for i in items.values())}
    out += [
        "insert into public.menu_categories (branch_id, name_ar, sort_order) values",
        ",\n".join(cat_values) + ";", "",
        "insert into public.menu_items (branch_id, category_id, name_ar, description_ar, advance_notice_hours, needs_review, sort_order)",
        "select v.branch_id, c.id, v.name_ar, v.description_ar, v.advance_notice_hours, v.needs_review, v.sort_order",
        "from (values", ",\n".join(item_values),
        ") as v (branch_id, category, name_ar, description_ar, advance_notice_hours, needs_review, sort_order)",
        "join public.menu_categories c on c.branch_id = v.branch_id and c.name_ar = v.category;", "",
        "insert into public.menu_item_sizes (item_id, label, price, sort_order)",
        "select i.id, v.label, v.price, v.sort_order",
        "from (values", ",\n".join(size_values),
        ") as v (branch_id, category, item, label, price, sort_order)",
        "join public.menu_categories c on c.branch_id = v.branch_id and c.name_ar = v.category",
        "join public.menu_items i on i.category_id = c.id and i.name_ar = v.item;", "",
    ]

    zone_values = []
    for b in meta["branches"]:
        for n, r in enumerate(rows(b["zones_file"]), start=1):
            active = r["status"] in ("ok", "review")
            zone_values.append("  (" + ", ".join([
                q(b["id"]), q(r["zone_type"]), q(r["zone_name"]), f"{r['fee_min']}::numeric", f"{r['fee_max']}::numeric",
                q(r["status"]), q(r["note"]), q(active), str(n)]) + ")")
    out += [
        "insert into public.delivery_zones (branch_id, zone_type, name_ar, fee, fee_max, review_status, note, is_active, sort_order) values",
        ",\n".join(zone_values) + ";", "",
        "commit;", "",
    ]
    return "\n".join(out), counts, len(zone_values)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sql, counts, zones = build()
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != sql:
            sys.exit("supabase/seed.sql is out of date: run python3 -I data/tools/build_seed.py")
        print("seed.sql is up to date")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(sql)
    print(f"wrote {OUT}: {counts} zones={zones}")


if __name__ == "__main__":
    main()
